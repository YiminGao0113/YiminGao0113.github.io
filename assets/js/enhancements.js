/* ==========================================================================
   Site-specific progressive enhancements.

   Kept separate from main.min.js (which is generated by `npm run uglify`
   from _main.js and theme.js) so template updates don't clobber it.

   Vanilla JS, no jQuery, no dependency on load order.
   ========================================================================== */

(function () {
  'use strict';

  var prefersReducedMotion =
    window.matchMedia &&
    window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function revealAll(elements) {
    for (var i = 0; i < elements.length; i++) {
      elements[i].classList.add('is-visible');
    }
  }

  function initReveal() {
    var targets = document.querySelectorAll('.reveal');
    if (!targets.length) {
      return;
    }

    // No IntersectionObserver, or the user wants less motion: show everything
    // immediately. The CSS transition is suppressed separately by the
    // prefers-reduced-motion media query, so this is just a visibility switch.
    if (prefersReducedMotion || !('IntersectionObserver' in window)) {
      revealAll(targets);
      return;
    }

    var observer = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            entry.target.classList.add('is-visible');
            observer.unobserve(entry.target);
          }
        });
      },
      { rootMargin: '0px 0px -8% 0px', threshold: 0.05 }
    );

    for (var i = 0; i < targets.length; i++) {
      observer.observe(targets[i]);
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initReveal);
  } else {
    initReveal();
  }
})();
